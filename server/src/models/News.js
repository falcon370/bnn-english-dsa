const mongoose = require('mongoose');

const commentSchema = new mongoose.Schema(
  {
    user: { type: mongoose.Schema.Types.ObjectId, ref: 'User', required: true },
    text: { type: String, required: true },
  },
  { timestamps: { createdAt: true, updatedAt: false } }
);

const sourceSchema = new mongoose.Schema(
  {
    source: { type: String },
    title: { type: String },
    snippet: { type: String },
    link: { type: String },
    imageUrl: { type: String },
    publishedAt: { type: String },
  },
  { _id: false }
);

const pulseAnalysisSchema = new mongoose.Schema(
  {
    positivePct:   { type: Number, default: 0 },
    negativePct:   { type: Number, default: 0 },
    neutralPct:    { type: Number, default: 0 },
    totalComments: { type: Number, default: 0 },
    topEmotion:    { type: String, default: null },
    emotionBreakdown: {
      joy:      { type: Number, default: 0 },
      trust:    { type: Number, default: 0 },
      surprise: { type: Number, default: 0 },
      fear:     { type: Number, default: 0 },
      anger:    { type: Number, default: 0 },
      sadness:  { type: Number, default: 0 },
    },
    keywords:       { type: [String], default: [] },
    topPositive:    { type: [String], default: [] },
    topNegative:    { type: [String], default: [] },
    aiSummary:      { type: String, default: null },
    keyTakeaway:    { type: String, default: null },
    dashboardSlug:  { type: String, default: null }, // used to serve /api/sentiment/dashboard/:slug
    generatedAt:    { type: Date, default: Date.now },
  },
  { _id: false }
);

const newsSchema = new mongoose.Schema(
  {
    topic: { type: String, required: true },
    title: { type: String },
    summary: { type: String, required: true },
    content: { type: String },
    category: { type: String, default: 'General' },
    tags: { type: [String], default: [] },
    interestOverTime: { type: mongoose.Schema.Types.Mixed, default: null },
    availableSources: { type: [String], default: [] },
    sourceOptions: { type: [sourceSchema], default: [] },
    selectedSource: { type: String, default: null },
    primarySource: { type: String, default: null },
    primaryLink: { type: String, default: null },
    imageUrl: { type: String, default: null },
    imageSource: { type: String, default: null },
    externalUrl: { type: String, default: null },
    status: {
      type: String,
      enum: ['draft', 'published'],
      default: 'draft',
    },
    publishedAt: { type: Date },
    sociallyPosted: { type: Boolean, default: false },
    facebookPosted: { type: Boolean, default: false },
    instagramPosted: { type: Boolean, default: false },
    isTrending: { type: Boolean, default: false },
    autoGenerated: { type: Boolean, default: false },
    fromNewsApi: { type: Boolean, default: false },
    createdBy: { type: mongoose.Schema.Types.ObjectId, ref: 'User', default: null },
    author: { type: mongoose.Schema.Types.ObjectId, ref: 'Author', default: null },
    comments: [commentSchema],
    reactions: [
      {
        user: { type: mongoose.Schema.Types.ObjectId, ref: 'User' },
        type: { type: String }, // e.g., 'like', 'love', 'haha', 'wow', 'sad', 'angry'
      }
    ],
    generatedAt: { type: Date, default: Date.now },
    // Pulse Analyzer — populated for Bolta Hai Bharat articles
    pulseAnalysis: { type: pulseAnalysisSchema, default: null },
    // Udaan retrieval layer (docs/UDAAN_VERTICAL_SPEC.md) — populated at
    // ingest time by server/src/services/udaan. select:false keeps these
    // off every existing route's response by default.
    embedding: { type: [Number], default: undefined, select: false }, // 384-d MiniLM, populated in M2
    minhashSignature: { type: [Number], default: undefined, select: false }, // 128 uint32 values, populated in M1
    arcId: { type: mongoose.Schema.Types.ObjectId, default: null, index: true },
    isArcRepresentative: { type: Boolean, default: true },
    arcUpdateCount: { type: Number, default: 0 },
  },
  { timestamps: true }
);

// Indexes for optimized query execution
newsSchema.index({ status: 1, publishedAt: -1 });
newsSchema.index({ category: 1, status: 1, publishedAt: -1 });
newsSchema.index({ isTrending: 1, generatedAt: -1 });

module.exports = mongoose.model('News', newsSchema);

